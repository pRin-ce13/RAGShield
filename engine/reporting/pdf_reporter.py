"""Executive PDF Security Assessment Report Generator for RAGShield.

Uses ReportLab Platypus to compile publication-quality PDF audit reports
featuring executive scorecards, OWASP compliance matrices, and engineering
remediation playbooks.
"""

from datetime import datetime, timezone
import io
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and print 'Page X of Y' footers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))  # Slate-500

        # Header (pages 2+)
        if self._pageNumber > 1:
            self.drawString(54, letter[1] - 36, "RAGShield Security Assessment Report")
            self.drawRightString(letter[0] - 54, letter[1] - 36, "Confidential Security Audit")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)

        # Footer (all pages)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 45, letter[0] - 54, 45)

        self.drawString(54, 32, "Confidential — Generated by RAGShield Security Platform")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 54, 32, page_str)
        self.restoreState()


def _get_severity_color(sev: str) -> colors.Color:
    s = (sev or "").upper()
    if s == "CRITICAL":
        return colors.HexColor("#DC2626")  # Red-600
    if s == "HIGH":
        return colors.HexColor("#D97706")  # Amber-600
    if s == "MEDIUM":
        return colors.HexColor("#CA8A04")  # Yellow-600
    return colors.HexColor("#2563EB")       # Blue-600


def _get_posture_bg_color(posture: str) -> colors.Color:
    p = (posture or "").upper()
    if "CRITICAL" in p:
        return colors.HexColor("#FEF2F2")  # Red-50
    if "HIGH" in p:
        return colors.HexColor("#FFFBEB")  # Amber-50
    if "MODERATE" in p:
        return colors.HexColor("#FEFCE8")  # Yellow-50
    return colors.HexColor("#F0FDF4")      # Emerald-50


def generate_pdf_report(
    report_data: Dict[str, Any],
    output_path: Optional[Union[str, Path]] = None
) -> bytes:
    """Generates an executive PDF report and writes to output_path or returns raw bytes.
    
    Args:
        report_data: Structured report dictionary from build_security_report().
        output_path: Optional path to save the PDF file.
        
    Returns:
        Raw PDF document bytes.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0F172A"),
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#475569"),
        spaceAfter=14,
    )
    heading2_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=colors.HexColor("#0F172A"),
        spaceBefore=12,
        spaceAfter=8,
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#334155"),
    )
    code_style = ParagraphStyle(
        "CodeText",
        parent=styles["Normal"],
        fontName="Courier",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#0F172A"),
    )
    badge_style = ParagraphStyle(
        "BadgeText",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.white,
        alignment=1,  # Center
    )

    story = []

    # 1. Title & Header
    story.append(Paragraph("RAG Application Security Assessment Report", title_style))
    gen_time = report_data.get("report_metadata", {}).get("generated_at", "")[:19].replace("T", " ")
    story.append(Paragraph(f"Executive Vulnerability Audit & Compliance Assessment • Generated: {gen_time} UTC", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceAfter=14))

    # 2. Target Details Table
    target = report_data.get("target_information", {})
    target_data = [
        [
            Paragraph("<b>Target System:</b>", body_style),
            Paragraph(target.get("target_name", "N/A"), body_style),
            Paragraph("<b>Scan Duration:</b>", body_style),
            Paragraph(f"{target.get('duration_seconds', 0.0):.1f}s", body_style),
        ],
        [
            Paragraph("<b>Endpoint URL:</b>", body_style),
            Paragraph(target.get("target_url", "N/A"), code_style),
            Paragraph("<b>Probes Run:</b>", body_style),
            Paragraph(str(target.get("completed_tests", 0)), body_style),
        ],
    ]
    target_table = Table(target_data, colWidths=[90, 200, 90, 124])
    target_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#F1F5F9")),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(target_table)
    story.append(Spacer(1, 14))

    # 3. Executive Posture Card
    exec_summary = report_data.get("executive_summary", {})
    posture = exec_summary.get("overall_posture", "SECURE")
    max_risk = exec_summary.get("max_risk_score", 0.0)
    sev_dist = exec_summary.get("severity_distribution", {})

    posture_data = [
        [
            Paragraph(f"<b>Overall Security Posture:</b> <font size=12><b>{posture}</b></font>", ParagraphStyle(
                "PostureTitle", parent=body_style, fontSize=11, leading=14, textColor=colors.HexColor("#0F172A")
            )),
            Paragraph(f"<b>Max Risk Score:</b> <font size=13 color='{_get_severity_color(posture).hexval()}'><b>{max_risk:.1f} / 10.0</b></font>", ParagraphStyle(
                "RiskScore", parent=body_style, fontSize=10, leading=13, alignment=2
            )),
        ],
        [
            Paragraph(
                f"<b>Severity Distribution:</b> "
                f"<font color='#DC2626'><b>{sev_dist.get('critical', 0)} Critical</b></font> | "
                f"<font color='#D97706'><b>{sev_dist.get('high', 0)} High</b></font> | "
                f"<font color='#CA8A04'><b>{sev_dist.get('medium', 0)} Medium</b></font> | "
                f"<font color='#2563EB'><b>{sev_dist.get('low', 0)} Low</b></font>",
                body_style
            ),
            Paragraph(
                f"Pass Rate: <b>{exec_summary.get('test_verdict_summary', {}).get('pass_rate_percentage', 0.0):.1f}%</b>",
                ParagraphStyle("PassRate", parent=body_style, alignment=2)
            ),
        ]
    ]
    posture_table = Table(posture_data, colWidths=[330, 174])
    posture_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), _get_posture_bg_color(posture)),
        ("BOX", (0, 0), (-1, -1), 1, _get_severity_color(posture)),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.append(posture_table)
    story.append(Spacer(1, 14))

    # 4. OWASP Compliance Matrix
    story.append(Paragraph("OWASP LLM Top 10 Coverage Matrix", heading2_style))
    matrix_rows = [
        [
            Paragraph("<b>OWASP Category</b>", body_style),
            Paragraph("<b>Tested</b>", body_style),
            Paragraph("<b>Passed</b>", body_style),
            Paragraph("<b>Failed</b>", body_style),
            Paragraph("<b>Status</b>", body_style),
        ]
    ]
    for item in report_data.get("owasp_compliance_matrix", []):
        is_compliant = item.get("compliance_status") == "COMPLIANT"
        status_color = "#16A34A" if is_compliant else "#DC2626"
        matrix_rows.append([
            Paragraph(item.get("category", ""), body_style),
            Paragraph(str(item.get("total_probes", 0)), body_style),
            Paragraph(str(item.get("passed_probes", 0)), body_style),
            Paragraph(str(item.get("failed_probes", 0)), body_style),
            Paragraph(f"<font color='{status_color}'><b>{item.get('compliance_status')}</b></font>", body_style),
        ])

    owasp_table = Table(matrix_rows, colWidths=[244, 60, 60, 60, 80])
    owasp_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("ALIGN", (1, 0), (-1, -1), "CENTER"),
    ]))
    story.append(owasp_table)
    story.append(Spacer(1, 16))

    # 5. Vulnerability Findings & Remediation Playbooks
    findings = report_data.get("vulnerability_findings", [])
    story.append(Paragraph(f"Deduplicated Vulnerability Findings ({len(findings)})", heading2_style))

    if not findings:
        story.append(Paragraph("✅ <i>No vulnerabilities identified. The target application conformed to evaluated security baselines.</i>", body_style))
    else:
        for idx, f in enumerate(findings, 1):
            finding_blocks = []
            sev = f.get("severity", "MEDIUM")
            sev_color = _get_severity_color(sev)

            # Finding Header Table (Title + Badges)
            hdr_cells = [
                [
                    Paragraph(f"<b>[{idx}] {f.get('title')}</b>", ParagraphStyle(
                        "FTitle", parent=body_style, fontSize=10, leading=13, fontName="Helvetica-Bold", textColor=colors.HexColor("#0F172A")
                    )),
                    Paragraph(f"<b>{sev}</b> (Risk: {f.get('risk_score', 0.0):.1f})", ParagraphStyle(
                        "FSev", parent=badge_style, textColor=sev_color, alignment=2
                    )),
                ],
                [
                    Paragraph(f"<font color='#64748B'>Finding ID: {f.get('finding_id')} | Category: {f.get('category')} | OWASP: {f.get('owasp_category') or 'N/A'}</font>", ParagraphStyle(
                        "FMeta", parent=body_style, fontSize=7.5, leading=9
                    )),
                    Paragraph(f"<font color='#64748B'>{f.get('evidence_count', 0)} vector(s) confirmed</font>", ParagraphStyle(
                        "FCount", parent=body_style, fontSize=7.5, leading=9, alignment=2
                    )),
                ]
            ]
            f_hdr_table = Table(hdr_cells, colWidths=[384, 120])
            f_hdr_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            finding_blocks.append(f_hdr_table)

            # Description
            desc_text = f"<b>Technical Summary:</b> {f.get('description')}"
            finding_blocks.append(Spacer(1, 4))
            finding_blocks.append(Paragraph(desc_text, body_style))

            # Forensic Evidence Snippets
            ev_instances = f.get("evidence_instances", [])
            if ev_instances:
                finding_blocks.append(Spacer(1, 3))
                finding_blocks.append(Paragraph("<b>Forensic Evidence Captured:</b>", body_style))
                for ev in ev_instances[:2]:
                    ev_text = f"• <b>[{ev.get('test_id')}]:</b> <font color='#DC2626'>{ev.get('evidence_snippet', '')[:120]}</font>"
                    finding_blocks.append(Paragraph(ev_text, ParagraphStyle("EvSnippet", parent=code_style, fontSize=7.5, leading=9)))

            # Remediation Playbook
            rem = f.get("remediation", {})
            rem_summary = rem.get("summary", "")
            finding_blocks.append(Spacer(1, 4))
            rem_box = [
                [Paragraph(f"<b>Remediation Recommendation:</b> {rem_summary}", body_style)],
            ]
            steps = rem.get("action_steps", [])
            if steps:
                steps_text = "<b>Action Steps:</b> " + " &nbsp;•&nbsp; ".join(steps[:3])
                rem_box.append([Paragraph(steps_text, ParagraphStyle("RemSteps", parent=body_style, fontSize=8, leading=10, textColor=colors.HexColor("#1E293B")))])

            rem_table = Table(rem_box, colWidths=[504])
            rem_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F0FDF4")),  # Emerald-50
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#BBF7D0")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ]))
            finding_blocks.append(rem_table)
            finding_blocks.append(Spacer(1, 10))

            story.append(KeepTogether(finding_blocks))

    # Build PDF with multi-pass NumberedCanvas
    doc.build(story, canvasmaker=NumberedCanvas)
    pdf_bytes = buffer.getvalue()
    buffer.close()

    if output_path:
        out = Path(output_path)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(pdf_bytes)

    return pdf_bytes
