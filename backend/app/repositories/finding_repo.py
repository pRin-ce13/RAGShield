"""Finding and Result Repository for Security Defects."""

import json
from typing import Any, Dict, List
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.models.finding import VulnerabilityFindingRecord
from backend.app.models.result import TestResultRecord
from backend.app.repositories.base import BaseRepository
from engine.evaluators.models import EvaluationResult
from engine.scoring.models import VulnerabilityFinding


class FindingRepository(BaseRepository[VulnerabilityFindingRecord]):
    """Data access layer for security findings and test results."""

    def __init__(self, session: AsyncSession):
        super().__init__(VulnerabilityFindingRecord, session)

    async def bulk_create_results(
        self,
        scan_run_id: str,
        evaluations: List[EvaluationResult]
    ) -> List[TestResultRecord]:
        """Bulk persists individual test evaluation records."""
        records: List[TestResultRecord] = []
        for e in evaluations:
            rec = TestResultRecord(
                scan_run_id=scan_run_id,
                test_id=e.test_id,
                test_name=e.test_name,
                category=e.category.value,
                owasp_category=e.owasp_category.value if e.owasp_category else None,
                severity=e.severity.value,
                status=e.status.value,
                confidence=e.confidence.value,
                evaluator_name=e.evaluator_name,
                evidence=e.evidence,
                reasoning=e.reasoning,
                target_role=e.target_role,
                latency_ms=e.response_latency_ms
            )
            self.session.add(rec)
            records.append(rec)

        await self.session.flush()
        return records

    async def bulk_create_findings(
        self,
        scan_run_id: str,
        findings: List[VulnerabilityFinding]
    ) -> List[VulnerabilityFindingRecord]:
        """Bulk persists deduplicated vulnerability findings."""
        records: List[VulnerabilityFindingRecord] = []
        for f in findings:
            rec = VulnerabilityFindingRecord(
                scan_run_id=scan_run_id,
                finding_id=f.finding_id,
                fingerprint=f.fingerprint,
                title=f.title,
                category=f.category.value,
                owasp_category=f.owasp_category.value if f.owasp_category else None,
                severity=f.severity.value,
                confidence=f.confidence.value,
                risk_score=f.risk_score,
                description=f.description,
                affected_target=f.affected_target,
                evidence_count=f.evidence_count,
                evidence_json=json.dumps([inst.model_dump() for inst in f.evidence_instances]),
                remediation_summary=f.remediation_summary,
                remediation_steps_json=json.dumps(f.remediation_steps),
                references_json=json.dumps(f.references)
            )
            self.session.add(rec)
            records.append(rec)

        await self.session.flush()
        return records

    async def get_by_scan_run(self, scan_run_id: str) -> List[VulnerabilityFindingRecord]:
        """Fetches all findings generated by a specific scan run, ordered by risk descending."""
        result = await self.session.execute(
            select(VulnerabilityFindingRecord)
            .where(VulnerabilityFindingRecord.scan_run_id == scan_run_id)
            .order_by(VulnerabilityFindingRecord.risk_score.desc())
        )
        return list(result.scalars().all())

    async def get_results_by_scan_run(self, scan_run_id: str) -> List[TestResultRecord]:
        """Fetches all raw test execution results for a scan run."""
        result = await self.session.execute(
            select(TestResultRecord)
            .where(TestResultRecord.scan_run_id == scan_run_id)
            .order_by(TestResultRecord.executed_at.asc())
        )
        return list(result.scalars().all())
